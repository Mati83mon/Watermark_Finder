/**
 * A stand-in for the analysis Space.
 *
 * `installEngineStub` replaces `globalThis.fetch` with a handler that serves
 * the engine's contract, so route tests exercise the real SpaceClient - retries,
 * timeouts, header handling - without a network.
 */

import type { AnalysisResult } from '@wf/shared';

export interface EngineStubOptions {
  /** Fail this many times before succeeding, to exercise retry logic. */
  failTimes?: number;
  /** Status returned while failing. */
  failStatus?: number;
  /** Reject at the transport level instead of returning a status. */
  networkError?: boolean;
  /** Override the analysis result. */
  result?: Partial<AnalysisResult>;
  /** Text returned by /extract. */
  extractText?: string;
  healthy?: boolean;
}

export interface EngineStub {
  calls: { path: string; method: string; body?: unknown }[];
  restore: () => void;
  options: EngineStubOptions;
}

