export function installEngineStub(options: EngineStubOptions = {}): EngineStub {
  const original = globalThis.fetch;
  const stub: EngineStub = { calls: [], restore: () => {}, options };
  let failures = 0;

  globalThis.fetch = (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = new URL(typeof input === 'string' ? input : input.toString());
    const method = init?.method ?? 'GET';
    stub.calls.push({ path: url.pathname, method });

    if (url.pathname === '/health') {
      return options.healthy === false
        ? new Response('down', { status: 503 })
        : Response.json({ status: 'ok', version: '1.0.0' });
    }

    if (url.pathname === '/capabilities') {
      return Response.json({
        modes: ['quick', 'forensic'],
        max_chars: 200000,
        max_upload_bytes: 10485760,
        perplexity_enabled: false,
        supported_uploads: ['.txt', '.pdf', '.docx'],
        auth_required: true,
      });
    }

    if (failures < (options.failTimes ?? 0)) {
      failures += 1;
      if (options.networkError) throw new TypeError('network failure');
      return new Response('engine busy', { status: options.failStatus ?? 503 });
    }

    if (url.pathname === '/extract') {
      return Response.json({
        request_id: 'stub',
        text: options.extractText ?? 'Extracted text from the uploaded document.',
        format: 'pdf',
        pages: 2,
        truncated: false,
        notes: [],
        chars: (options.extractText ?? 'Extracted text from the uploaded document.').length,
      });
    }

    if (url.pathname === '/sanitize') {
      const body = init?.body ? JSON.parse(String(init.body)) : {};
      stub.calls[stub.calls.length - 1]!.body = body;
      const text = String(body.text ?? '');
      // Mirror the engine closely enough to be useful: drop tag characters,
      // count what went, and leave everything else alone.
      const cleaned = [...text].filter((ch) => {
        const cp = ch.codePointAt(0)!;
        return !(cp >= 0xe0000 && cp <= 0xe007f);
      }).join('');
      const removedTotal = [...text].length - [...cleaned].length;
      return Response.json({
        request_id: 'stub',
        text: cleaned,
        level: body.level ?? 'safe',
        changed: removedTotal > 0,
        removed: [],
        removed_total: removedTotal,
        replaced: [],
        replaced_total: 0,
        preserved: [],
        preserved_total: 0,
        warnings: [],
      });
    }

    if (url.pathname === '/mark') {
      const body = init?.body ? JSON.parse(String(init.body)) : {};
      stub.calls[stub.calls.length - 1]!.body = body;
      const recipients: string[] = body.recipients ?? [];
      const template: string = body.template ?? '{recipient}';
      return Response.json({
        request_id: 'stub',
        channel: body.channel ?? 'tag_characters',
        copies: recipients.map((recipient, i) => {
          const payload = template
            .replace('{recipient}', recipient)
            .replace(/\{index[^}]*\}/, String(i + 1));
          const carrier = [...payload]
            .map((ch) => String.fromCodePoint(0xe0000 + ch.charCodeAt(0)))
            .join('');
          return {
            recipient,
            payload,
            text: `${body.text}${carrier}`,
            channel: body.channel ?? 'tag_characters',
            carrier_chars: [...carrier].length,
            copies_embedded: body.repeat ?? 2,
            verified: true,
          };
        }),
        warnings: ['Exporting to PDF destroys the mark.'],
      });
    }

    if (url.pathname === '/analyze') {
      const body = init?.body ? JSON.parse(String(init.body)) : {};
      stub.calls[stub.calls.length - 1]!.body = body;
      return Response.json({
        request_id: 'stub',
        client_reference: body.client_reference ?? null,
        result: makeResult({
          ...options.result,
          engine: {
            ...makeResult().engine,
            mode: body.mode ?? 'forensic',
            ...(options.result?.engine ?? {}),
          },
        }),
      });
    }

    return new Response('not found', { status: 404 });
  }) as typeof fetch;

  stub.restore = () => {
    globalThis.fetch = original;
  };
  return stub;
}
